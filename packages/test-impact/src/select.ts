import { existsSync, readFileSync } from "node:fs";
import { join, matchesGlob, relative } from "node:path";
import { ALL, RISK, type Config, type Risk } from "./config.js";

export interface Reason {
  file: string;
  rule: string;
  risk: Risk;
}

export interface Selection {
  /** True when the whole suite must run. */
  fullRun: boolean;
  /** tag or feature title → why it was selected. */
  selected: Map<string, Reason[]>;
  always: string[];
  unmapped: string[];
  ignored: string[];
  /** Changed files outside the suite that no rule mentions. */
  outside: string[];
  risk: Risk | null;
}

/**
 * @param changed repo-relative paths
 * @param suiteDir the config file's directory, repo-relative ("" for the root)
 * @param repoRoot absolute repo root, to read changed feature files
 */
export function select(config: Config, changed: string[], suiteDir: string, repoRoot: string): Selection {
  const sel: Selection = {
    fullRun: false,
    selected: new Map(),
    always: config.always,
    unmapped: [],
    ignored: [],
    outside: [],
    risk: null,
  };
  const add = (key: string, reason: Reason) => {
    sel.selected.set(key, [...(sel.selected.get(key) ?? []), reason]);
    sel.risk = maxRisk(sel.risk, reason.risk);
    if (key === ALL) sel.fullRun = true;
  };

  for (const file of changed) {
    const rel = relative(suiteDir || ".", file) || file;
    const inSuite = !rel.startsWith("..");
    const matches = (glob: string) => matchesGlob(rel, glob);

    if (config.ignore.some(matches)) {
      sel.ignored.push(rel);
      continue;
    }

    let mapped = false;
    for (const rule of config.rules) {
      if (!rule.paths.some(matches)) continue;
      mapped = true;
      for (const tag of rule.tags) add(tag, { file: rel, rule: rule.name, risk: rule.risk });
    }

    if (inSuite && matches(config.features)) {
      mapped = true;
      const title = featureTitle(join(repoRoot, file));
      // A deleted feature has no title and no tests left to run.
      if (title) add(title, { file: rel, rule: "changed feature", risk: "medium" });
    }

    if (!mapped) (inSuite ? sel.unmapped : sel.outside).push(rel);
  }

  if (sel.unmapped.length > 0 && config.unmapped === "all") {
    sel.fullRun = true;
    sel.risk = "high";
  }
  return sel;
}

/** Test titles generated by playwright-bdd start with the Feature name, so it works as a --grep term. */
function featureTitle(path: string): string | null {
  if (!existsSync(path)) return null;
  const m = readFileSync(path, "utf-8").match(/^\s*Feature:\s*(.+?)\s*$/m);
  return m ? m[1] : null;
}

function maxRisk(a: Risk | null, b: Risk): Risk {
  if (!a) return b;
  return RISK.indexOf(a) <= RISK.indexOf(b) ? a : b;
}

/** A --grep pattern matching any selected tag or feature title, or null for a full run. */
export function grepPattern(sel: Selection): string | null {
  if (sel.fullRun) return null;
  const terms = [...new Set([...sel.always, ...sel.selected.keys()])];
  return terms.map((t) => (t.startsWith("@") ? `${escape(t)}\\b` : escape(t))).join("|");
}

function escape(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
